"""Pydantic schemas and contracts for Grounded LLM Answer Generation (Phase 8)."""

from datetime import datetime
from typing import List, Optional
from pydantic import BaseModel, ConfigDict, Field

from app.modules.retrieval.schemas import EmployeeContext
from app.schemas.common import current_utc_time


class CitationItem(BaseModel):
    """Structured citation linking answer claims back to authoritative source policy documents."""

    model_config = ConfigDict(populate_by_name=True)

    citation_label: str = Field(description="Normalized citation label matching source context, e.g. '[Source 1]'")
    citation_reference: str = Field(
        description="Full formatted source reference, e.g. '[Source 1: Leave Policy, pages 2–3, Sick Leave]'"
    )
    document_id: str = Field(description="Authoritative document UUID")
    document_name: str = Field(description="Policy document title or sanitized filename")
    version: int = Field(default=1, ge=1, description="Document revision version")
    page_start: int = Field(ge=1, description="First source PDF page number")
    page_end: int = Field(ge=1, description="Last source PDF page number")
    heading: Optional[str] = Field(default=None, description="Immediate section heading")


class LLMAnswerRaw(BaseModel):
    """Schema representing the raw structured response expected from the LLM provider."""

    model_config = ConfigDict(populate_by_name=True)

    answer: str = Field(description="Grounded natural language answer based exclusively on context")
    citations: List[str] = Field(
        default_factory=list,
        description="List of citation label strings referenced in the answer, e.g. ['[Source 1]']",
    )
    insufficient_evidence: bool = Field(
        default=False,
        description="Flag indicating whether available context is insufficient to answer the question",
    )
    conflicting_evidence: bool = Field(
        default=False,
        description="Flag indicating whether conflicting policies or provisions were detected",
    )
    limitations: Optional[str] = Field(
        default=None,
        description="Explanation of missing information, ambiguities, or policy contradictions",
    )


class AnswerRequest(BaseModel):
    """Public API request schema for grounded question answering."""

    model_config = ConfigDict(populate_by_name=True)

    question: str = Field(
        min_length=1,
        description="Natural language question regarding HR policies",
    )
    employee_context: Optional[EmployeeContext] = Field(
        default=None,
        description="Optional employee categorization for personalized applicability filtering",
    )
    as_of_date: Optional[datetime] = Field(
        default=None,
        description="Optional evaluation date for policy effectiveness (defaults to current UTC time)",
    )
    top_k: int = Field(
        default=10,
        ge=1,
        le=50,
        description="Maximum number of candidate chunks to retrieve before reranking and context assembly",
    )
    token_budget: Optional[int] = Field(
        default=None,
        ge=100,
        le=16000,
        description="Optional token budget override for context window assembly",
    )


class AnswerResponse(BaseModel):
    """Public API response schema representing a grounded, cited policy answer."""

    model_config = ConfigDict(populate_by_name=True)

    question: str = Field(description="Original user question as submitted")
    answer: str = Field(description="Grounded policy answer generated by the LLM")
    citations: List[CitationItem] = Field(
        default_factory=list,
        description="Validated citation references strictly matching the authoritative source manifest",
    )
    insufficient_evidence: bool = Field(
        default=False,
        description="True if the available policies do not provide sufficient information to fully answer",
    )
    conflicting_evidence: bool = Field(
        default=False,
        description="True if policies contain conflicting provisions or overlapping contradictory rules",
    )
    limitations: Optional[str] = Field(
        default=None,
        description="Explanation of missing information, ambiguities, or policy conflicts",
    )
    context_tokens: int = Field(ge=0, description="Total tokens utilized in the assembled context")
    model_name: str = Field(description="Name or deployment ID of the generative model used")
    status: str = Field(
        default="success",
        description="Generation status indicator ('success', 'insufficient_evidence', 'empty_context')",
    )
    created_at: datetime = Field(
        default_factory=current_utc_time,
        description="UTC timestamp of answer generation",
    )
